const fs = require("fs");
const path = require("path");

const PHOTOS_DIR = path.join(__dirname, "../app/Food/data/recipe/photos");
const OUTPUT_FILE = path.join(PHOTOS_DIR, "index.ts");
const VALID_EXT = [".jpg", ".jpeg", ".png", ".webp"];

const files = fs
  .readdirSync(PHOTOS_DIR)
  // Use precomposed accents (é, not e + ◌́) to match git and the recipe ids;
  // macOS may list names decomposed, which breaks the build on Linux.
  .map((f) => f.normalize("NFC"))
  .filter((f) => VALID_EXT.includes(path.extname(f).toLowerCase()))
  .filter((f) => f !== "placeholder.jpeg"); // handled separately below

const entries = files
  .map((file) => {
    const id = path.basename(file, path.extname(file));
    return `  "${id}": require("./${file}"),`;
  })
  .join("\n");

const content = `// AUTO-GENERATED by scripts/generate-photo-index.js — do not edit by hand.
// Run "npm run generate:photos" after adding/removing images in this folder.

const photos: Record<string, any> = {
${entries}
};

const placeholder = require("./placeholder.jpeg");

export const getRecipePhoto = (id: string) => photos[id] ?? placeholder;
`;

fs.writeFileSync(OUTPUT_FILE, content);
console.log(`✓ Generated ${files.length} photo entries in ${OUTPUT_FILE}`);